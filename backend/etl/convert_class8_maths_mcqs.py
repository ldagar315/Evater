"""Deterministically convert answer-keyed NCERT maths items into MCQ candidates.

Owner decision (2026-10-21, approved over WhatsApp): wrong options are
generated by fixed rules from the official answer - no LLM - and every
converted item passes a QC gate before it can be staged as publishable.

Rules:
- Only items whose official answer is a single numeric value (optionally with
  a short unit like "m", "m^2", "cm", "%") are eligible. Multi-part, textual,
  or roman-numeral answers stay in the item archive.
- Distractors come from a fixed rule pool (off-by-one/two, doubling/halving,
  place-value slips, digit reversal, +-10%, common-operation slips) sampled
  deterministically from the source question id.
- QC gate: exactly 4 distinct options, key text equals the official answer,
  stem unchanged from the extracted item. Failures are skipped, never forced.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import re
from pathlib import Path
from typing import Any

from .models import CandidateOption, QuestionCandidate, QuestionItemCandidate
from .scrape_class8_maths import MATHS_SOURCE_ID_PREFIX, TEXTBOOK_SHORT, NCERT_LICENSE
from .scrape_class8_science import _bounded, _normalize, _now

_UNIT_RE = re.compile(r"^\s*(-?[\d,]+(?:\.\d+)?)\s*([a-zA-Z^0-9%\u00b0]{0,10})\s*$")


def _parse_single_number(answer: str) -> tuple[float, str, str] | None:
    """Parse an official answer into (value, unit, canonical_text) or None."""

    cleaned = answer.strip()
    currency = ""
    if cleaned.startswith("\u20b9"):
        currency = "\u20b9"
        cleaned = cleaned[1:].strip()
    match = _UNIT_RE.match(cleaned)
    if not match:
        return None
    digits = match.group(1).replace(",", "")
    unit = (currency + match.group(2).strip()).strip()
    if unit.startswith("^"):
        return None  # power-form answers like 2^75 make meaningless distractors
    try:
        value = float(digits)
    except ValueError:
        return None
    canonical = digits.rstrip("0").rstrip(".") if "." in digits else digits
    return value, unit, canonical


def _format_like(value: float, reference: str) -> str:
    if "." in reference:
        decimals = len(reference.split(".")[1])
        return f"{value:.{decimals}f}"
    if value == int(value):
        return str(int(value))
    return f"{value:g}"


def _reverse_digits(reference: str) -> float | None:
    if not reference.isdigit() or len(reference) < 2:
        return None
    reversed_digits = reference[::-1].lstrip("0")
    if not reversed_digits or reversed_digits == reference:
        return None
    return float(reversed_digits)


def _distractor_pool(value: float, reference: str) -> list[float]:
    pool: list[float] = [
        value + 1,
        value - 1,
        value + 2,
        value * 2,
        value / 2,
        value * 10,
        value / 10,
        value * 1.1,
        value * 0.9,
        value**2 if abs(value) <= 1000 else value + 10,
        value + 5,
        value - 10,
    ]
    reversed_value = _reverse_digits(reference)
    if reversed_value is not None:
        pool.append(reversed_value)
    if value < 0:
        pool.append(-value)
    return pool


_PART_RE = re.compile(r"\((i{1,3}|iv|vi{0,2})\)")
_TRAILING_VALUE_RE = re.compile(r"=\s*(-?[\d,]+(?:\.\d+)?)\s*([a-zA-Z0-9^%\u00b0]{0,10})\s*$")


def _split_parts(answer: str) -> list[tuple[str | None, str]]:
    """Split a multi-part official answer into (part_label, fragment) pieces."""

    markers = list(_PART_RE.finditer(answer))
    if not markers:
        return [(None, answer)]
    parts: list[tuple[str | None, str]] = []
    for index, marker in enumerate(markers):
        end = markers[index + 1].start() if index + 1 < len(markers) else len(answer)
        parts.append((marker.group(1), answer[marker.end() : end].strip(" .;,")))
    return parts


def _fragment_value(fragment: str) -> tuple[float, str, str] | None:
    """Parse a fragment as a bare number or one ending in '= value'."""

    parsed = _parse_single_number(fragment)
    if parsed is not None:
        return parsed
    if fragment.count("=") != 1:
        return None  # multi-assignment fragments (cryptarithms etc.) are not single values
    trailing = _TRAILING_VALUE_RE.search(fragment)
    if trailing and not trailing.group(2).startswith("^"):
        digits = trailing.group(1).replace(",", "")
        try:
            value = float(digits)
        except ValueError:
            return None
        canonical = digits.rstrip("0").rstrip(".") if "." in digits else digits
        return value, trailing.group(2).strip(), canonical
    return None


_STEM_BLEED_MARKERS = (
    "A Shortcut for",
    "Math Talk",
    "Figure it Out",
    "Math  Talk",
    "Summary",
)


def _clean_stem(stem: str) -> str:
    """Cut prose/section-heading bleed from the end of an extracted stem."""

    for marker in _STEM_BLEED_MARKERS:
        if marker in stem:
            stem = stem.split(marker, 1)[0]
    stem = re.split(r"\s\d+\.\d+\s+[A-Z]", stem)[0]
    return stem.strip()


_DOUBLE_PART_LABEL_RE = re.compile(r"\((?:i{1,3}|iv|vi?|x)\)\s*\((?:i{1,3}|iv|vi?|x)\)")


def _stem_is_publishable(stem: str) -> bool:
    """Reject stems broken at extraction level (detached part labels, fragments)."""

    if _DOUBLE_PART_LABEL_RE.search(stem):
        return False
    if stem.rstrip().endswith(("—", "-", ":", ",")):
        return False
    if len(stem) < 20:
        return False
    return True


def convert_item(item: QuestionItemCandidate) -> list[QuestionCandidate]:
    """Convert one answer-keyed item to MCQ candidates (one per numeric part)."""

    answer = (item.explanation or "").strip()
    conversions: list[QuestionCandidate] = []
    for part_label, fragment in _split_parts(answer):
        parsed = _fragment_value(fragment)
        if parsed is None:
            continue
        candidate = _convert_value(item, parsed, answer, part_label)
        if candidate is not None:
            conversions.append(candidate)
    return conversions


def _convert_value(
    item: QuestionItemCandidate,
    parsed: tuple[float, str, str],
    full_answer: str,
    part_label: str | None,
) -> QuestionCandidate | None:
    value, unit, canonical = parsed
    value, unit, canonical = parsed
    seed_material = f"{item.source_question_id or item.question_text}:{part_label or ''}"
    seed = int(hashlib.sha256(seed_material.encode("utf-8")).hexdigest()[:12], 16)
    rng = random.Random(seed)

    seen = {canonical}
    distractors: list[str] = []
    for candidate_value in _distractor_pool(value, canonical):
        formatted = _format_like(candidate_value, canonical)
        if formatted in seen or not formatted or formatted.startswith("-"):
            continue
        seen.add(formatted)
        distractors.append(formatted)
        if len(distractors) == 12:
            break
    if len(distractors) < 3:
        return None
    rng.shuffle(distractors)
    chosen = distractors[:3]

    if unit.startswith("\u20b9"):
        prefix = "\u20b9"
        rest = unit[1:].strip()
        suffix = f" {rest}" if rest else ""
    else:
        prefix = ""
        suffix = f" {unit}" if unit else ""
    option_texts = [prefix + canonical + suffix] + [prefix + text + suffix for text in chosen]
    letters = ["A", "B", "C", "D"]
    order = list(range(4))
    rng.shuffle(order)
    options = [
        {"id": letters[position], "text": option_texts[original_index]}
        for position, original_index in enumerate(order)
    ]
    correct_letter = letters[order.index(0)]

    # QC gate: 4 distinct options, key present, stem untouched.
    texts = [option["text"] for option in options]
    if len(set(texts)) != 4 or options[letters.index(correct_letter)]["text"] != prefix + canonical + suffix:
        return None

    stem = item.question_text if part_label is None else f"{item.question_text} (part ({part_label}))"
    stem = _clean_stem(stem)
    if not _stem_is_publishable(stem):
        return None
    question_family = f"ganita-mcq:{item.chapter_id}:{hashlib.sha1(_normalize(stem).encode()).hexdigest()[:12]}"
    prov = (item.answer_spec or {}).get("answer_provenance")
    verification_note = (item.answer_spec or {}).get("verification") or ""
    if prov == "self_solved_verified":
        explanation_text = f"Answer computed and independently verified by Evater's deterministic solver. Check: {verification_note}."
        attribution_text = f"NCERT, {TEXTBOOK_SHORT} (ncert.nic.in); answer self-solved and verified by Evater; options derived deterministically"
        verification_value = f"self_solved_verified: {verification_note}"
    else:
        explanation_text = f"Official NCERT answer key: {full_answer}."
        attribution_text = f"NCERT, {TEXTBOOK_SHORT} (ncert.nic.in); options derived deterministically from the official answer key"
        verification_value = "official_answer_key"

    return QuestionCandidate(
        chapter_id=item.chapter_id,
        concept_id=item.concept_id,
        question_text=_bounded(stem, 1000),
        options=[CandidateOption(id=option["id"], text=_bounded(option["text"], 500)) for option in options],
        correct_option_id=correct_letter,  # type: ignore[arg-type]
        explanation=_bounded(explanation_text, 2000),
        hint=None,
        difficulty=item.difficulty,
        cognitive_level="apply",
        skill_tags=sorted(set(item.skill_tags) | {"deterministic_mcq"}),
        misconception_tags=[],
        question_style="direct",  # type: ignore[arg-type]
        estimated_time_seconds=item.estimated_time_seconds,
        marks=item.marks,
        source_url=item.source_url,
        source_locator=item.source_locator,
        source_question_id=(
            f"{item.source_question_id}:mcq:{part_label}" if part_label else f"{item.source_question_id}:mcq"
        ) if item.source_question_id else None,
        source_tier="ncert_attributed",
        rework_status="done",
        source_license=NCERT_LICENSE,
        source_attribution=attribution_text,
        question_family_key=question_family,
        variant_key="deterministic_mcq_conversion",
        answer_spec={
            "type": "mcq_single",
            "source_answer": prefix + canonical + suffix,
            "verification": verification_value,
            "answer_provenance": (item.answer_spec or {}).get("answer_provenance"),
            "answer_source_url": item.source_url,
            "conversion": "deterministic_rules_from_official_key",
        },
        generation_spec={
            "ingestion_method": "deterministic_mcq_conversion",
            "source_item_id": item.source_question_id,
            "retrieved_at": _now(),
            "verification_state": "qc_checked",
        },
        license_status="review_required",
        review_status="review",
    )


def convert_pack(pack: dict[str, Any]) -> dict[str, Any]:
    """Append converted MCQ candidates to a scraped pack's questions list."""

    items = [QuestionItemCandidate(**raw) for raw in pack.get("items", [])]
    existing_ids = {question.get("source_question_id") for question in pack.get("questions", [])}
    converted: list[dict[str, Any]] = []
    for item in items:
        if not item.answer_spec.get("has_answer_key"):
            continue
        if item.question_type not in {"numerical", "short_answer"}:
            continue
        for candidate in convert_item(item):
            if candidate.source_question_id in existing_ids:
                continue
            converted.append(candidate.model_dump(mode="json"))
    updated = dict(pack)
    updated["questions"] = list(pack.get("questions", [])) + converted
    updated["mcq_conversion"] = {
        "method": "deterministic_rules_from_official_key",
        "converted_count": len(converted),
    }
    return updated


def main() -> int:
    parser = argparse.ArgumentParser(description="Convert answer-keyed maths items into deterministic MCQ candidates.")
    parser.add_argument("--packs-dir", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--chapters", default="1-14")
    args = parser.parse_args()

    selected = set()
    for part in args.chapters.split(","):
        part = part.strip()
        if "-" in part:
            start, end = (int(piece) for piece in part.split("-", 1))
            selected.update(range(start, end + 1))
        elif part:
            selected.add(int(part))

    args.out_dir.mkdir(parents=True, exist_ok=True)
    reports = []
    for chapter in sorted(selected):
        path = args.packs_dir / f"class8_maths_scraped_chapter_{chapter:02d}.json"
        if not path.exists():
            reports.append({"chapter": chapter, "error": "pack missing"})
            continue
        updated = convert_pack(json.loads(path.read_text(encoding="utf-8")))
        out_path = args.out_dir / path.name
        out_path.write_text(json.dumps(updated, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        reports.append(
            {
                "chapter": chapter,
                "mcq_total": len(updated["questions"]),
                "converted": updated["mcq_conversion"]["converted_count"],
                "pack": str(out_path),
            }
        )
    print(json.dumps({"reports": reports}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
